const Glyph* findGlyph(char raw) {
    char code = raw;
    if (code >= 'a' && code <= 'z') {
        code = static_cast<char>(code - 'a' + 'A');
    }
    for (const Glyph& glyph : kFont) {
        if (glyph.code == code) return &glyph;
    }
    for (const Glyph& glyph : kFont) {
        if (glyph.code == '?') return &glyph;
    }
    return nullptr;
}

